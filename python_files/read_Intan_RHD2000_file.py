import struct
import os
import time
import numpy as np
from tkinter import Tk, filedialog


# ---------------------------------------------------------------------------
# Helper: read Qt-style QString
# ---------------------------------------------------------------------------

def read_qstring(fid):
    """
    Read a Qt-style QString from an open binary file.
    The first uint32 gives the byte length of the string.
    0xFFFFFFFF means the string is null/empty.
    """
    length_bytes = fid.read(4)
    if len(length_bytes) < 4:
        return ''
    length = struct.unpack('<I', length_bytes)[0]
    if length == 0xFFFFFFFF:
        return ''
    # Length is in bytes; each Unicode character is 2 bytes (UTF-16LE)
    num_chars = length // 2
    chars = []
    for _ in range(num_chars):
        word = struct.unpack('<H', fid.read(2))[0]
        chars.append(chr(word))
    return ''.join(chars)


# ---------------------------------------------------------------------------
# Helper: notch filter
# ---------------------------------------------------------------------------

def notch_filter(signal, f_sample, f_notch, bandwidth):
    """
    Implements a notch filter (e.g. 50 or 60 Hz) on a 1-D array.

    Parameters
    ----------
    signal    : 1-D numpy array
    f_sample  : sample rate (Hz)
    f_notch   : notch frequency (Hz)
    bandwidth : notch 3-dB bandwidth (Hz); 10 Hz is recommended

    Returns
    -------
    out : filtered 1-D numpy array
    """
    tstep = 1.0 / f_sample
    Fc = f_notch * tstep
    L = len(signal)

    d = np.exp(-2.0 * np.pi * (bandwidth / 2.0) * tstep)
    b = (1.0 + d * d) * np.cos(2.0 * np.pi * Fc)
    a0 = 1.0
    a1 = -b
    a2 = d * d
    a = (1.0 + d * d) / 2.0
    b0 = 1.0
    b1 = -2.0 * np.cos(2.0 * np.pi * Fc)
    b2 = 1.0

    out = np.zeros(L)
    out[0] = signal[0]
    if L > 1:
        out[1] = signal[1]

    for i in range(2, L):
        out[i] = (
            a * b2 * signal[i - 2]
            + a * b1 * signal[i - 1]
            + a * b0 * signal[i]
            - a2 * out[i - 2]
            - a1 * out[i - 1]
        ) / a0

    return out


# ---------------------------------------------------------------------------
# Helper: read a typed scalar from the file
# ---------------------------------------------------------------------------

_FMT = {
    'uint32': ('<I', 4),
    'int16':  ('<h', 2),
    'uint16': ('<H', 2),
    'int32':  ('<i', 4),
    'single': ('<f', 4),
}

def fread_scalar(fid, dtype):
    fmt, size = _FMT[dtype]
    return struct.unpack(fmt, fid.read(size))[0]


